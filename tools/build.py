#!/usr/bin/env python3
"""Rebuild DIMORA from the modules in src/.

Outputs (repo root = the deployable static site):
  index.html, css/style.css, js/app.js, js/main.js, assets/logo.svg
  dist/dimora.html  -> the same app bundled into ONE self-contained file
Usage:  python3 tools/build.py      (or: npm run build:src)
"""
import glob, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, 'src')
tpl = open(os.path.join(src, '00_template.html'), encoding='utf-8').read()
css = open(os.path.join(src, 'style.css'), encoding='utf-8').read()
mods = sorted(glob.glob(os.path.join(src, '0*.js')))
app = "/* DIMORA app bundle (generated by tools/build.py — edit files in src/) */\n(function(){'use strict';\n" + "\n".join(open(f, encoding='utf-8').read() for f in mods) + "\n})();\n"
main = open(os.path.join(src, 'main.js'), encoding='utf-8').read()
for d in ('css', 'js', 'assets', 'dist'): os.makedirs(os.path.join(root, d), exist_ok=True)
def w(p, s): open(os.path.join(root, p), 'w', encoding='utf-8').write(s)
w('css/style.css', css); w('js/app.js', app); w('js/main.js', main)
w('index.html', tpl.replace('<style>/*CSS*/</style>', '<link rel="stylesheet" href="css/style.css">')
                  .replace('<script>/*JS*/</script>', '<script src="js/app.js"></script>\n<script src="js/main.js"></script>'))
w('assets/logo.svg', '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#c084fc"/><stop offset=".5" stop-color="#818cf8"/><stop offset="1" stop-color="#22d3ee"/></linearGradient></defs><path d="M16 2 29 9.5v13L16 30 3 22.5v-13z" fill="none" stroke="url(#g)" stroke-width="2.2"/><path d="M16 9 23 13v7l-7 4-7-4v-7z" fill="url(#g)" opacity=".85"/></svg>\n')
w('dist/dimora.html', tpl.replace('/*CSS*/', css).replace('<script>/*JS*/</script>', '<script>' + app.replace('</script', '<\\/script') + '</script>\n<script>' + main + '</script>'))
print('Built index.html, css/, js/, assets/ and dist/dimora.html')
